"""
Regenerate benchmarks/BENCHMARK_RESULTS.md from benchmarks/results.json.

The report is generated, never hand-written. The previous BENCHMARK_RESULTS.md
was maintained by hand and drifted badly away from the code that was supposed
to produce it: it credited NumPy's rank to "LAPACK" when the benchmark actually
ran a hand-written Python loop, quoted SVD timings that no script in the repo
produced, and printed a headline of "75-90% less memory" directly above a table
showing gf2 using 60% *more* at 500x500.

Usage:
    python benchmarks/bench_gf2.py            # measure -> results.json
    python benchmarks/make_report.py          # results.json -> BENCHMARK_RESULTS.md
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent


def rows_for(op: dict) -> list[tuple[str, float, float, float, str]]:
    out = []
    for name, r in op["results"].items():
        if "run" not in r:
            continue
        out.append(
            (
                name,
                r["run"]["min_ms"],
                r["run"]["median_ms"],
                r["memory"]["peak_mib"],
                op["equivalence"].get(name, "?"),
            )
        )
    return out


def main() -> None:
    data = json.loads((HERE / "results.json").read_text())
    env = data["environment"]
    ops = data["operations"]

    lines: list[str] = []
    add = lines.append

    add("# Benchmark Results")
    add("")
    add(
        "**Generated by `benchmarks/make_report.py` from `benchmarks/results.json`.** "
        "Do not edit by hand - rerun `benchmarks/bench_gf2.py` and regenerate."
    )
    add("")
    add(f"Measured {date.today().isoformat()} on:")
    add("")
    add("```")
    for k, v in env.items():
        add(f"{k:<10} {v}")
    add("```")
    add("")
    add("## How these numbers were taken")
    add("")
    add(
        "- **Timing and memory are separate passes.** `tracemalloc` inflates wall time by "
        "14-28x on this codebase, and unevenly across implementations, so anything timed "
        "while it runs is not a timing of the algorithm."
    )
    add(
        "- **Minimum of N runs after a warm-up.** For deterministic CPU work the minimum is "
        "the sample least contaminated by scheduler noise. The median is printed beside it; "
        "if the two diverge, the measurement was unstable and should not be quoted."
    )
    add(
        "- **Outputs are checked for equivalence** before any speed claim. The `=?` column is "
        "that check. For nullspace it verifies `A @ x == 0` and `x != 0` rather than comparing "
        "vectors, since different algorithms legitimately pick different free variables."
    )
    add(
        "- **Setup is timed separately** from the operation, so building each library's native "
        "matrix type is never silently charged to one side."
    )
    add(
        "- **Two NumPy baselines.** `numpy-packed` is bit-packed uint64 rows with vectorised "
        "XOR elimination - what a competent NumPy user writes for GF(2), and the only baseline "
        "a speed claim should be made against. `numpy-naive` is element-wise uint8 indexing; it "
        "is reported only to show the gap between the two NumPy styles. **Beating `numpy-naive` "
        "proves nothing.**"
    )
    add(
        "- **`galois null_space` does more work** than the gf2 and NumPy nullspace entries: it "
        "computes the full basis and we take one vector. That is noted in the table, not hidden."
    )
    add("")
    add("## Results")
    add("")

    for op in ops:
        add(f"### {op['operation']}  (density {op['density']})")
        add("")
        add("| implementation | min ms | median ms | peak MiB | correct | note |")
        add("|---|---:|---:|---:|:---:|---|")
        table = rows_for(op)
        for name, mn, md, mem, eq in table:
            note = op["results"][name].get("note", "")
            add(f"| {name} | {mn:.3f} | {md:.3f} | {mem:.3f} | {eq} | {note} |")
        add("")
        if table:
            fastest = min(table, key=lambda t: t[1])
            gf2_rows = [t for t in table if t[0].startswith("gf2")]
            if gf2_rows:
                b = gf2_rows[0]
                if fastest[0] == b[0]:
                    runner = sorted(t for t in table if t[0] != b[0])
                    if runner:
                        nxt = min((t for t in table if t[0] != b[0]), key=lambda t: t[1])
                        add(f"gf2 is fastest here, by {nxt[1] / b[1]:.2f}x over {nxt[0]}.")
                else:
                    add(f"{fastest[0]} is fastest here; gf2 is {b[1] / fastest[1]:.2f}x slower.")
        add("")

    (HERE / "BENCHMARK_RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {HERE / 'BENCHMARK_RESULTS.md'} ({len(ops)} operations)")


if __name__ == "__main__":
    main()
